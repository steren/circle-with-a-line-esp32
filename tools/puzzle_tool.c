// PC-side tool for Circle with a Line. Builds the same puzzle and game code as the
// firmware, so what passes here is what runs on the board.
//
//   puzzle_tool check                      self-test the rules, and generate many puzzles for
//                                              every level to check they are solvable and how
//                                              long generating takes
//   puzzle_tool gen COLS ROWS RULES SEED   generate one puzzle and print it as a text map
//   puzzle_tool bank FILE.c COUNT          generate COUNT puzzles for every level into a C file
//                                              RULES: any of n (counts) g (gems) b (beacons) x (gaps)
//   puzzle_tool shots DIR                  play the levels with simulated touches and save
//                                              screenshots as DIR/*.ppm
//   puzzle_tool sound FILE.wav             render the game's sounds to a WAV file and check them

