static long count_solutions(const puzzle_t *p, long limit, puzzle_path_t *first)
{
    return puzzle_count_solutions(p, limit, 0, first, NULL);
}

static uint32_t s_rng = 1;

static int rnd(int n)
{
    s_rng ^= s_rng << 13;
    s_rng ^= s_rng >> 17;
    s_rng ^= s_rng << 5;
    return (int)(s_rng % (uint32_t)n);
}

// ---- Text maps ----

static void print_map(const puzzle_t *p, FILE *out)
{
    for (int y = 0; y <= 2 * p->rows; y++) {
        fputs("    \"", out);
        for (int x = 0; x <= 2 * p->cols; x++) {
            const int row = y / 2, col = x / 2;
            char ch;
            if (y % 2 == 0 && x % 2 == 0) {
                const int node = puzzle_node(p, row, col);
                ch = p->is_start[node] ? 'S' : p->is_exit[node] ? 'E' : p->node_beacon[node] ? 'o' : '+';
            } else if (y % 2 == 0) {
                ch = p->h_edges[row][col] == EDGE_GAP ? ' ' : p->h_edges[row][col] == EDGE_BEACON ? 'o' : '-';
            } else if (x % 2 == 0) {
                ch = p->v_edges[row][col] == EDGE_GAP ? ' ' : p->v_edges[row][col] == EDGE_BEACON ? 'o' : '|';
            } else {
                const puzzle_cell_t *cell = &p->cells[row][col];
                ch = cell->kind == CELL_COUNT     ? '0' + cell->value
                     : cell->kind == CELL_GEM     ? 'a' + cell->value
                     : cell->kind == CELL_STAR    ? 'A' + cell->value
                     : cell->kind == CELL_POLY    ? 'd' + cell->value
                     : cell->kind == CELL_NEGATOR ? 'Y'
                                                  : ' ';
            }
            fputc(ch, out);
        }
        fputs(y < 2 * p->rows ? "\\n\"\n" : "\",\n", out);
    }
}

static int cmd_gen(int cols, int rows, const char *rules, uint32_t seed)
{
    if (cols < 1 || rows < 1 || cols > PUZZLE_MAX_COLS || rows > PUZZLE_MAX_ROWS) {
        fprintf(stderr, "size must be 1..%d x 1..%d\n", PUZZLE_MAX_COLS, PUZZLE_MAX_ROWS);
        return 1;
    }
    const puzzle_spec_t spec = {cols, rows, rules};
    uint32_t state = seed * 2654435761u + 1;
    puzzle_t p;
    puzzle_gen_stats_t stats;
    puzzle_generate(&p, &spec, &state, LEVEL_GENERATION_STEPS, &stats);
    const long solutions = count_solutions(&p, 1000, NULL);
    printf("    // %dx%d, rules \"%s\", seed %u: %d clues, %ld%s solution%s, %d attempts, %ld solver steps\n", cols,
           rows, rules, seed, stats.clues, solutions, solutions >= 1000 ? "+" : "", solutions == 1 ? "" : "s",
           stats.attempts, stats.solver_steps);
    print_map(&p, stdout);
    return solutions > 0 ? 0 : 1;
}

// Steps allowed per bank puzzle: generous, since this runs on the PC.
#define BANK_GENERATION_STEPS 3000000

static int cmd_bank(const char *file, int count)
{
    FILE *out = fopen(file, "w");
    if (!out) {
        perror(file);
        return 1;
    }
    fprintf(out, "// Generated by `make game-bank` (tools/puzzle_tool.c): %d puzzles for every\n"
                 "// level, each checked to have exactly one solution. Do not edit by hand.\n\n"
                 "#include \"puzzle_bank.h\"\n\n", count);
    uint32_t seed = 99;
    int failures = 0;
    for (int i = 0; i < level_count; i++) {
        const puzzle_spec_t *spec = &levels[i];
        fprintf(out, "// Level %d: %dx%d, rules \"%s\"\nstatic const char *const level%d[] = {\n", i + 1, spec->cols,
                spec->rows, spec->rules, i + 1);
        int made = 0;
        for (int tries = 0; made < count && tries < 20 * count; tries++) {
            puzzle_t p;
            puzzle_gen_stats_t stats;
            puzzle_generate(&p, spec, &seed, BANK_GENERATION_STEPS, &stats);
            if (spec->rules[0] && count_solutions(&p, 2, NULL) != 1) {
                continue;  // only puzzles with exactly one solution go in the bank
            }
            print_map(&p, out);
            made++;
        }
        fprintf(out, "};\n\n");
        printf("level %2d: %d puzzles\n", i + 1, made);
        failures += made < count;
    }
    fprintf(out, "const puzzle_bank_t puzzle_bank[] = {\n");
    for (int i = 0; i < level_count; i++) {
        fprintf(out, "    {level%d, sizeof(level%d) / sizeof(level%d[0])},\n", i + 1, i + 1, i + 1);
    }
    fprintf(out, "};\n\nconst int puzzle_bank_levels = sizeof(puzzle_bank) / sizeof(puzzle_bank[0]);\n");
    fclose(out);
    return failures ? 1 : 0;
}

// ---- Self-test and level check ----

#define EXPECT(condition)                                               \
    do {                                                                \
        if (!(condition)) {                                             \
            printf("FAILED %s:%d: %s\n", __FILE__, __LINE__, #condition); \
            failures++;                                                 \
        }                                                               \
    } while (0)

static bool walk(const puzzle_t *p, puzzle_path_t *path, const char *moves)
{
    puzzle_path_start(path, puzzle_first_start(p));
    for (; *moves; moves++) {
        const puzzle_dir_t dir = *moves == 'U' ? DIR_UP : *moves == 'D' ? DIR_DOWN : *moves == 'L' ? DIR_LEFT : DIR_RIGHT;
        if (puzzle_path_step(p, path, dir) == STEP_BLOCKED) {
            return false;
        }
    }
    return true;
}

static int self_test(void)
{
    int failures = 0;
    puzzle_t p;
    puzzle_path_t path;
    puzzle_result_t result;

    // Parsing
    EXPECT(!puzzle_parse(&p, "+-+\n| |\n+-+"));         // no start or exit
    EXPECT(!puzzle_parse(&p, "S-+\n| |\n+-E-"));        // ragged rows
    EXPECT(!puzzle_parse(&p, "S-+\n|9|\n+-E"));         // unknown clue
    EXPECT(puzzle_parse(&p, "S-+\n| |\n+-E"));
    EXPECT(p.cols == 1 && p.rows == 1 && p.is_start[0] && p.is_exit[3] && !p.is_exit[0]);
    EXPECT(!puzzle_parse(&p, "S-+-+\n| | |\n+-E-+\n| | |\n+-+-+"));  // an exit off the border

    EXPECT(puzzle_parse(&p, "S-+-E\n| | |\n+-+-+\n| | |\n+-+-+"));
    EXPECT(puzzle_exit_dir(&p, 2) == DIR_UP);
    EXPECT(puzzle_parse(&p, "S-+-+\n| | |\n+-+-E\n| | |\n+-+-+"));
    EXPECT(puzzle_exit_dir(&p, 5) == DIR_RIGHT);

    // Movement: forward, undo, no revisits, gaps, nothing past the exit
    EXPECT(puzzle_parse(&p, "+-+-E\n| |  \n+-+-+\n| | |\nS-+-+"));
    EXPECT(walk(&p, &path, "RU") && path.length == 3);
    EXPECT(puzzle_path_step(&p, &path, DIR_DOWN) == STEP_BACK && path.length == 2);
    EXPECT(walk(&p, &path, "RUL") && puzzle_path_step(&p, &path, DIR_DOWN) == STEP_BLOCKED);  // back onto the start
    EXPECT(!walk(&p, &path, "RRUU"));                   // the top right line is a gap
    EXPECT(!walk(&p, &path, "L") && !walk(&p, &path, "D"));  // off the board
    EXPECT(walk(&p, &path, "UURR") && puzzle_path_step(&p, &path, DIR_LEFT) == STEP_BACK);


    // The line stops at the exit
    EXPECT(walk(&p, &path, "UURR") && puzzle_path_step(&p, &path, DIR_DOWN) == STEP_BLOCKED);

    // A path must end on the exit
    EXPECT(walk(&p, &path, "UUR") && !puzzle_check(&p, &path, NULL));
    EXPECT(walk(&p, &path, "UURR") && puzzle_check(&p, &path, NULL));

    // Beacons on a node and on a line
    EXPECT(puzzle_parse(&p, "+-+-E\n| | |\n+-o-+\n| | o\nS-+-+"));
    EXPECT(walk(&p, &path, "UURR") && !puzzle_check(&p, &path, &result));
    EXPECT(result.missed_node[4] && result.missed_v[1][2]);
    EXPECT(walk(&p, &path, "RURU") && !puzzle_check(&p, &path, &result) && !result.missed_node[4]);
    EXPECT(walk(&p, &path, "URDRUU") && puzzle_check(&p, &path, NULL));

    // Counts
    EXPECT(puzzle_parse(&p, "+-+-E\n|2|0|\n+-+-+\n| |3|\nS-+-+"));
    EXPECT(walk(&p, &path, "UURR") && !puzzle_check(&p, &path, &result));
    EXPECT(!result.bad_cell[0][0] && result.bad_cell[0][1] && result.bad_cell[1][1]);
    EXPECT(puzzle_parse(&p, "+-+-E\n|2|1|\n+-+-+\n| |0|\nS-+-+"));
    EXPECT(walk(&p, &path, "UURR") && puzzle_check(&p, &path, NULL));
    EXPECT(puzzle_cell_sides(&p, &path, 0, 0) == 2 && puzzle_cell_sides(&p, &path, 1, 1) == 0);

    // Gems and areas
    EXPECT(puzzle_parse(&p, "+-+-E\n|a|b|\n+-+-+\n|a|b|\nS-+-+"));
    uint8_t region[PUZZLE_MAX_ROWS][PUZZLE_MAX_COLS];
    EXPECT(walk(&p, &path, "UURR") && puzzle_regions(&p, &path, region) == 1);
    EXPECT(!puzzle_check(&p, &path, &result) && result.bad_cell[0][0] && result.bad_cell[1][1]);
    EXPECT(walk(&p, &path, "RUUR") && puzzle_regions(&p, &path, region) == 2);
    EXPECT(region[0][0] == region[1][0] && region[0][1] == region[1][1] && region[0][0] != region[0][1]);
    EXPECT(puzzle_check(&p, &path, NULL));
    EXPECT(count_solutions(&p, 100, NULL) == 2);  // straight up the middle, or around it

    // Solver: a 2x2 board has 12 paths between opposite corners
    EXPECT(puzzle_parse(&p, "+-+-E\n| | |\n+-+-+\n| | |\nS-+-+"));
    EXPECT(count_solutions(&p, 100, NULL) == 12);

    // Stars: each star needs exactly two symbols of its colour in its area
    EXPECT(puzzle_parse(&p, "+-+-E\n|A|A|\n+-+-+\n|A|A|\nS-+-+"));
    EXPECT(walk(&p, &path, "UURR") && !puzzle_check(&p, &path, &result));  // all 4 in one area -> count is 4, not 2
    EXPECT(walk(&p, &path, "URRU") && puzzle_check(&p, &path, NULL));      // splits top 1x2 (2 A's) from bottom 1x2 (2 A's)

    // Polyominoes: area must match the shape's exact blocks
    EXPECT(puzzle_parse(&p, "+-+-E\n|e| |\n+-+-+\n| |f|\nS-+-+"));
    EXPECT(walk(&p, &path, "URRU") && !puzzle_check(&p, &path, &result));  // bottom is 1x2 (e), not 2x1 (f)
    EXPECT(puzzle_parse(&p, "+-+-E\n|e| |\n+-+-+\n| |e|\nS-+-+"));
    EXPECT(walk(&p, &path, "URRU") && puzzle_check(&p, &path, NULL));

    // Negators: cancels one broken symbol in its area, fails if nothing is broken
    EXPECT(puzzle_parse(&p, "+-+-E\n|Y|3|\n+-+-+\n| | |\nS-+-+"));
    EXPECT(walk(&p, &path, "UURR") && puzzle_check(&p, &path, NULL));      // 3 is broken (has 1 side), Y cancels it
    EXPECT(puzzle_parse(&p, "+-+-E\n|Y|1|\n+-+-+\n| | |\nS-+-+"));
    EXPECT(walk(&p, &path, "UURR") && !puzzle_check(&p, &path, &result));  // 1 is already valid, so Y has nothing to cancel

    return failures;
}

static int cmd_check(void)
{
    int failures = self_test();
    printf("rules self-test: %s\n", failures ? "FAILED" : "ok");

    // Generate many puzzles for every level. Each must be solvable; report how
    // often the solution is unique and how much work generating took.
    enum { SAMPLES = 100 };
    uint32_t seed = 2024;
    printf("level  size  rules  unique  clues  steps avg / max   attempts max  time max\n");
    for (int i = 0; i < level_count; i++) {
        const puzzle_spec_t *spec = &levels[i];
        int unique = 0, clues = 0, max_attempts = 0, unsolvable = 0;
        long steps = 0, max_steps = 0;
        double max_ms = 0;
        for (int k = 0; k < SAMPLES; k++) {
            puzzle_t p;
            puzzle_gen_stats_t stats;
            const clock_t begin = clock();
            puzzle_generate(&p, spec, &seed, LEVEL_GENERATION_STEPS, &stats);
            const double ms = 1000.0 * (clock() - begin) / CLOCKS_PER_SEC;
            if (ms > max_ms) max_ms = ms;
            const long solutions = count_solutions(&p, 2, NULL);
            if (solutions == 0) unsolvable++;
            // The generator may fail to prove a puzzle unique in its step budget,
            // but must never claim uniqueness wrongly.
            if (stats.unique && solutions != 1) {
                printf("level %d: generator says one solution but the puzzle has %ld\n", i + 1, solutions);
                failures++;
            }
            unique += solutions == 1;
            clues += stats.clues;
            steps += stats.solver_steps;
            if (stats.solver_steps > max_steps) max_steps = stats.solver_steps;
            if (stats.attempts > max_attempts) max_attempts = stats.attempts;
        }
        printf("%5d  %dx%d   %-5s  %3d%%   %5.1f  %8ld / %8ld  %12d  %6.1f ms%s\n", i + 1, spec->cols, spec->rows,
               spec->rules[0] ? spec->rules : "-", unique * 100 / SAMPLES, (double)clues / SAMPLES, steps / SAMPLES,
               max_steps, max_attempts, max_ms, unsolvable ? "  <-- UNSOLVABLE PUZZLES" : "");
        failures += unsolvable;
    }
    // The bank: one entry per level, every puzzle the right size and with one solution.
    if (puzzle_bank_levels != level_count) {
        printf("puzzle bank has %d levels, the game %d: run make game-bank\n", puzzle_bank_levels, level_count);
        failures++;
    } else {
        int bank_total = 0;
        for (int i = 0; i < level_count; i++) {
            for (int k = 0; k < puzzle_bank[i].count; k++, bank_total++) {
                puzzle_t p;
                if (!puzzle_parse(&p, puzzle_bank[i].maps[k]) || p.cols != levels[i].cols || p.rows != levels[i].rows ||
                    count_solutions(&p, 2, NULL) != (levels[i].rules[0] ? 1 : 2)) {
                    printf("bank puzzle %d for level %d is wrong: run make game-bank\n", k + 1, i + 1);
                    failures++;
                }
            }
        }
        printf("puzzle bank: %d puzzles checked\n", bank_total);
    }
    printf("%s\n", failures ? "FAILED" : "all levels ok");
    return failures ? 1 : 0;
}

// ---- Screenshots from simulated play ----

static uint16_t s_framebuffer[GAME_SCREEN_WIDTH * GAME_SCREEN_HEIGHT];
static uint32_t s_now_ms;
static int s_sounds[GAME_SOUND_LEVEL + 1];  // how often each sound was requested
static game_sound_t s_last_sound;

static void count_sound(game_sound_t sound)
{
    s_sounds[sound]++;
    s_last_sound = sound;
}

static void save_screenshot(const char *dir, const char *name)
{
    char file[512];
    snprintf(file, sizeof(file), "%s/%s.ppm", dir, name);
    FILE *out = fopen(file, "wb");
    if (!out) {
        perror(file);
        exit(1);
    }
    fprintf(out, "P6\n%d %d\n255\n", GAME_SCREEN_WIDTH, GAME_SCREEN_HEIGHT);
    for (int i = 0; i < GAME_SCREEN_WIDTH * GAME_SCREEN_HEIGHT; i++) {
        const uint16_t c = __builtin_bswap16(s_framebuffer[i]);
        const uint8_t rgb[3] = {(c >> 11) << 3, ((c >> 5) & 0x3F) << 2, (c & 0x1F) << 3};
        fwrite(rgb, 1, 3, out);
    }
    fclose(out);
}

static void tick(bool pressed, int x, int y, int times)
{
    for (int i = 0; i < times; i++) {
        const game_touch_t touch = {pressed, x, y};
        game_update(&touch, s_now_ms);
        s_now_ms += 10;
    }
}

// Drags a finger along the first `steps` moves of a path, in straight lines
// between nodes, leaving it down at the end.
static void drag(const puzzle_path_t *path, int steps)
{
    int x, y;
    game_node_position(path->nodes[0], &x, &y);
    tick(true, x, y, 2);
    for (int i = 1; i <= steps && i < path->length; i++) {
        int next_x, next_y;
        game_node_position(path->nodes[i], &next_x, &next_y);
        for (int t = 1; t <= 4; t++) {
            tick(true, x + (next_x - x) * t / 4, y + (next_y - y) * t / 4, 1);
        }
        x = next_x;
        y = next_y;
    }
}

// Plays a solution the way a real finger would: never quite on the line,
// cutting every corner, and overshooting. `wobble` is how far off the line
// the finger strays, as a percentage of a cell.
static void drag_sloppily(const puzzle_t *p, const puzzle_path_t *path, int wobble)
{
    int x0, y0, x1, y1;
    game_node_position(path->nodes[0], &x0, &y0);
    game_node_position(path->nodes[1], &x1, &y1);
    const int stray = (abs(x1 - x0) + abs(y1 - y0)) * wobble / 100;
    (void)p;

    int x = x0, y = y0;
    tick(true, x, y, 2);
    for (int i = 1; i < path->length; i++) {
        int next_x, next_y;
        game_node_position(path->nodes[i], &next_x, &next_y);
        next_x += rnd(2 * stray + 1) - stray;
        next_y += rnd(2 * stray + 1) - stray;
        for (int t = 1; t <= 5; t++) {
            tick(true, x + (next_x - x) * t / 5, y + (next_y - y) * t / 5, 1);
        }
        x = next_x;
        y = next_y;
    }
    // Finish squarely on the exit.
    game_node_position(path->nodes[path->length - 1], &x, &y);
    tick(true, x, y, 2);
    tick(false, 0, 0, 5);
}

static int cmd_shots(const char *dir)
{
    int failures = 0;
    gfx_init(s_framebuffer, GAME_SCREEN_WIDTH, GAME_SCREEN_HEIGHT);
    game_init(7);

    // Every level, twenty times each at three levels of sloppiness.
    s_rng = 12345;
    for (int wobble = 10; wobble <= 30; wobble += 10) {
        int solved = 0, total = 0;
        for (int i = 0; i < level_count; i++) {
            for (int attempt = 0; attempt < 20; attempt++, total++) {
                game_load_level(i);  // a new puzzle every time
                const puzzle_t *p = game_puzzle();
                puzzle_path_t solution;
                count_solutions(p, 1, &solution);
                drag_sloppily(p, &solution, wobble);
                solved += game_is_solved();
                tick(false, 0, 0, 120);  // let a wrong answer clear
            }
        }
        printf("sloppy finger, straying up to %d%% of a cell: solved %d of %d\n", wobble, solved, total);
        if (wobble <= 20 && solved != total) {
            failures++;
        }
    }

    game_load_level(0);
    game_set_sound_handler(count_sound);

    int played = 0;
    for (int i = 0; i < level_count; i++) {
        char name[64];
        if (game_level() != i) {
            printf("level %d: game is on level %d instead\n", i + 1, game_level() + 1);
            failures++;
            game_load_level(i);
        }
        puzzle_path_t solution;
        if (count_solutions(game_puzzle(), 1, &solution) != 1) {
            printf("level %d: the generated puzzle is unsolvable\n", i + 1);
            failures++;
            continue;
        }
        if (solution.length < 3) {
            continue;  // too short to stop halfway
        }
        snprintf(name, sizeof(name), "level%02d_start", i + 1);
        save_screenshot(dir, name);

        // Trace half of the solution, lift the finger, pick the path up again and finish it.
        // The finger stops 40% of the way to the next node; lifting it there
        // lets the tip fall back to the node it came from.
        const int half = solution.length / 2;
        drag(&solution, half);
        int x, y, next_x, next_y;
        game_node_position(solution.nodes[half], &x, &y);
        if (half + 1 < solution.length) {
            game_node_position(solution.nodes[half + 1], &next_x, &next_y);
            tick(true, x + (next_x - x) * 4 / 10, y + (next_y - y) * 4 / 10, 2);
        }
        snprintf(name, sizeof(name), "level%02d_tracing", i + 1);
        save_screenshot(dir, name);
        if (s_last_sound != GAME_SOUND_TRACE) {
            printf("level %d: the hum should be on while the finger is down\n", i + 1);
            failures++;
        }
        tick(false, 0, 0, 5);
        if (s_last_sound != GAME_SOUND_LIFT) {
            printf("level %d: lifting the finger should stop the hum\n", i + 1);
            failures++;
        }
        tick(true, x, y, 2);
        for (int n = solution.length / 2 + 1; n < solution.length; n++) {
            game_node_position(solution.nodes[n], &x, &y);
            tick(true, x, y, 2);
        }
        tick(false, 0, 0, 5);
        if (!game_is_solved()) {
            printf("level %d: playing the solution by touch did not solve it\n", i + 1);
            failures++;
        }
        if (s_last_sound != GAME_SOUND_SOLVED) {
            printf("level %d: the last sound should be the solved phrase, not %d\n", i + 1, s_last_sound);
            failures++;
        }
        played++;
        snprintf(name, sizeof(name), "level%02d_solved", i + 1);
        save_screenshot(dir, name);
        tick(false, 0, 0, 200);  // wait for the next level to load
    }

    // Moving the line only redraws part of the screen. Drag out and back, then
    // lift the finger (which redraws everything) and check nothing changed.
    {
        game_load_level(level_count - 1);
        puzzle_path_t solution;
        count_solutions(game_puzzle(), 1, &solution);
        static uint16_t partial[GAME_SCREEN_WIDTH * GAME_SCREEN_HEIGHT];
        drag(&solution, solution.length - 2);
        int x, y;
        for (int n = solution.length - 3; n >= 1; n--) {
            game_node_position(solution.nodes[n], &x, &y);
            tick(true, x, y, 3);
        }
        memcpy(partial, s_framebuffer, sizeof(partial));
        tick(false, 0, 0, 5);
        long differ = 0;
        for (int i = 0; i < GAME_SCREEN_WIDTH * GAME_SCREEN_HEIGHT; i++) {
            differ += partial[i] != s_framebuffer[i];
        }
        if (differ) {
            printf("redrawing only the line left %ld pixels different from a full redraw\n", differ);
            save_screenshot(dir, "partial_redraw_mismatch");
            failures++;
        }
        s_sounds[GAME_SOUND_LIFT]--;  // not part of the sound counts below
        s_sounds[GAME_SOUND_TRACE]--;
    }

    // A wrong answer: on the last level, find a path to the exit that breaks the rules.
    game_load_level(level_count - 1);
    const puzzle_t p = *game_puzzle();
    puzzle_t no_clues = p;
    memset(no_clues.cells, 0, sizeof(no_clues.cells));
    memset(no_clues.node_beacon, 0, sizeof(no_clues.node_beacon));
    puzzle_path_t wrong;
    if (count_solutions(&no_clues, 1, &wrong) == 1 && !puzzle_check(&p, &wrong, NULL)) {
        drag(&wrong, wrong.length);
        tick(false, 0, 0, 5);
        if (game_is_solved()) {
            printf("a wrong path was accepted\n");
            failures++;
        }
        save_screenshot(dir, "wrong_answer");
    }
    if (s_sounds[GAME_SOUND_SOLVED] != played || s_sounds[GAME_SOUND_FAILED] != 1 ||
        s_sounds[GAME_SOUND_LIFT] != played || s_sounds[GAME_SOUND_TRACE] != 2 * played + 1) {
        printf("unexpected sounds: %d solved, %d failed, %d lifts for %d levels played\n",
               s_sounds[GAME_SOUND_SOLVED], s_sounds[GAME_SOUND_FAILED], s_sounds[GAME_SOUND_LIFT], played);
        failures++;
    }

    // Buttons: stepping between puzzles stops at both ends, and reset clears the line.
    game_load_level(0);
    game_previous_level();
    if (game_level() != 0 || s_sounds[GAME_SOUND_LEVEL] != 0) {
        printf("previous on the first puzzle should do nothing\n");
        failures++;
    }
    game_next_level();
    game_next_level();
    game_previous_level();
    if (game_level() != 1 || s_sounds[GAME_SOUND_LEVEL] != 3) {
        printf("next, next, previous should land on puzzle 2 with three sounds\n");
        failures++;
    }
    game_load_level(level_count - 1);
    game_next_level();
    if (game_level() != level_count - 1) {
        printf("next on the last puzzle should do nothing\n");
        failures++;
    }

    printf("%s\n", failures ? "FAILED" : "simulated play ok");
    return failures ? 1 : 0;
}

// ---- Sound: render what the board would play ----

static FILE *s_wav;
static long s_wav_samples;

typedef struct {
    int peak, max_jump;  // loudest sample, and biggest change between two neighbouring samples
    double energy;
    long count;
    int last;
} sound_stats_t;

static void render(int ms, sound_stats_t *stats)
{
    for (int left = SYNTH_SAMPLE_RATE * ms / 1000; left > 0;) {
        int16_t samples[64];
        const int n = left < 64 ? left : 64;
        synth_render(samples, n);
        fwrite(samples, sizeof(int16_t), n, s_wav);
        s_wav_samples += n;
        left -= n;
        for (int i = 0; stats && i < n; i++) {
            if (abs(samples[i]) > stats->peak) stats->peak = abs(samples[i]);
            if (abs(samples[i] - stats->last) > stats->max_jump) stats->max_jump = abs(samples[i] - stats->last);
            stats->last = samples[i];
            stats->energy += (double)samples[i] * samples[i];
            stats->count++;
        }
    }
}

static int report(const char *label, const sound_stats_t *stats, int min_peak, int max_peak, int max_jump)
{
    const bool ok = stats->peak >= min_peak && stats->peak <= max_peak && stats->max_jump <= max_jump;
    printf("%-34s peak %5d  rms %6.0f  biggest jump %5d  %s\n", label, stats->peak,
           stats->count ? sqrt(stats->energy / stats->count) : 0.0, stats->max_jump, ok ? "ok" : "<-- UNEXPECTED");
    return ok ? 0 : 1;
}

static int cmd_sound(const char *file)
{
    s_wav = fopen(file, "wb");
    if (!s_wav) {
        perror(file);
        return 1;
    }
    uint8_t header[44] = {0};
    fwrite(header, 1, sizeof(header), s_wav);
    int failures = 0;

    // Drawing a line for two seconds, then lifting the finger.
    sound_stats_t hum = {0}, tail = {0}, silence = {0};
    synth_hum_on();
    render(2000, &hum);
    synth_hum_off();
    render(300, &tail);
    // The hum's own waveform changes by up to about 2000 between samples;
    // anything well beyond that would be a click.
    failures += report("hum while drawing", &hum, 3000, 16000, 2500);
    failures += report("hum fading out after lift", &tail, 100, 16000, 2500);
    if (!synth_is_silent()) {
        printf("the hum should have faded out 300 ms after the finger lifted\n");
        failures++;
    }
    render(300, &silence);
    failures += report("silence", &silence, 0, 0, 0);

    // Solving straight from drawing: the hum gives way to the phrase.
    sound_stats_t solved = {0}, failed = {0}, buttons = {0}, cut = {0};
    synth_hum_on();
    render(400, NULL);
    synth_hum_off();
    synth_phrase(GAME_SOUND_SOLVED);
    render(900, &solved);
    failures += report("solved phrase", &solved, 4000, 20000, 6000);
    synth_phrase(GAME_SOUND_FAILED);
    render(700, &failed);
    failures += report("wrong-answer phrase", &failed, 4000, 20000, 6000);
    synth_phrase(GAME_SOUND_LEVEL);
    render(300, &buttons);
    failures += report("button phrases", &buttons, 4000, 20000, 6000);

    // One phrase cutting off another must not click.
    synth_phrase(GAME_SOUND_SOLVED);
    render(120, &cut);
    synth_phrase(GAME_SOUND_LEVEL);
    render(400, &cut);
    failures += report("phrase cut off by another", &cut, 4000, 20000, 6000);
    if (!synth_is_silent()) {
        printf("everything should be silent at the end\n");
        failures++;
    }

    // Fill in the WAV header: 16-bit mono PCM.
    const uint32_t data_bytes = (uint32_t)s_wav_samples * 2, rate = SYNTH_SAMPLE_RATE;
    const uint32_t fields[] = {36 + data_bytes, 16, 1 | (1 << 16), rate, rate * 2, 2 | (16 << 16), data_bytes};
    memcpy(header, "RIFF", 4);
    memcpy(header + 4, &fields[0], 4);
    memcpy(header + 8, "WAVEfmt ", 8);
    memcpy(header + 16, &fields[1], 20);
    memcpy(header + 36, "data", 4);
    memcpy(header + 40, &fields[6], 4);
    fseek(s_wav, 0, SEEK_SET);
    fwrite(header, 1, sizeof(header), s_wav);
    fclose(s_wav);

    printf("%s (%.1f s written to %s)\n", failures ? "FAILED" : "sounds ok", (double)s_wav_samples / rate, file);
    return failures ? 1 : 0;
}

int main(int argc, char **argv)
{
    if (argc == 2 && strcmp(argv[1], "check") == 0) {
        return cmd_check();
    }
    if (argc == 6 && strcmp(argv[1], "gen") == 0) {
        return cmd_gen(atoi(argv[2]), atoi(argv[3]), argv[4], (uint32_t)strtoul(argv[5], NULL, 10));
    }
    if (argc == 3 && strcmp(argv[1], "shots") == 0) {
        return cmd_shots(argv[2]);
    }
    if (argc == 4 && strcmp(argv[1], "bank") == 0) {
        return cmd_bank(argv[2], atoi(argv[3]));
    }
    if (argc == 3 && strcmp(argv[1], "sound") == 0) {
        return cmd_sound(argv[2]);
    }
    fprintf(stderr, "usage: %s check | gen COLS ROWS RULES SEED | shots DIR | sound FILE.wav\n", argv[0]);
    return 2;
}
